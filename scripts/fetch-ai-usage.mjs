// Refreshes src/data/ai-usage-snapshot.ts from the published AI usage dashboard.
//
// This is the only place the resume repo reads the dashboard, and it runs at build or
// on a schedule, never at runtime. The committed snapshot is the artifact the site and
// the AI surfaces consume, so a reviewer can always see which figures were live when.
//
// Source of truth: https://sam-rogers.com/ai-usage/ embeds its full daily record as
// window.__DAILY_BURN__. If the producer ever publishes /ai-usage/summary.json this
// script prefers it; until then it derives the same headline figures from the daily
// record. Any parse failure exits non-zero and leaves the committed snapshot untouched.

import { readFile, writeFile } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = resolve(root, "src/data/ai-usage-snapshot.ts");
const DASHBOARD_URL = "https://sam-rogers.com/ai-usage/";
const SUMMARY_URL = `${DASHBOARD_URL}summary.json`;

const SOURCE_LABELS = {
  claude_api: "Anthropic API",
  claude_chat: "Claude chat",
  claude_code: "Claude Code",
  claude_cowork: "Claude Cowork",
  claude_design: "Claude Design",
  chatgpt: "ChatGPT",
  openai_api: "OpenAI API",
  codex: "Codex",
  perplexity_api: "Perplexity API",
  qwen_local: "Qwen (local)",
  gemma_local: "Gemma (local)",
  kilo: "Kilo",
  snapdev: "Snapdev",
};

async function fetchText(url) {
  const res = await fetch(url, { headers: { "user-agent": "resume-ai-usage-refresh" } });
  if (!res.ok) throw new Error(`${url} returned ${res.status}`);
  return res.text();
}

function extractGlobal(html, name) {
  const marker = `window.${name} = `;
  const start = html.indexOf(marker);
  if (start < 0) throw new Error(`${name} not found in dashboard HTML`);
  const from = start + marker.length;
  // The globals are emitted as `window.X = <json>;` on one line each.
  const end = html.indexOf(";\n", from) >= 0 ? html.indexOf(";\n", from) : html.indexOf("; window.", from);
  const raw = html.slice(from, end < 0 ? undefined : end).trim().replace(/;$/, "");
  return JSON.parse(raw);
}

function summarizeDaily(daily) {
  let exact = 0;
  let estimated = 0;
  const sources = new Set();
  let minDate = "9999-99-99";
  let maxDate = "0000-00-00";
  for (const day of daily) {
    if (day.date < minDate) minDate = day.date;
    if (day.date > maxDate) maxDate = day.date;
    for (const [id, entry] of Object.entries(day.sources ?? {})) {
      sources.add(id);
      if (entry.fidelity === "exact") exact += entry.tokens;
      else estimated += entry.tokens;
    }
  }
  return {
    asOf: maxDate,
    firstDate: minDate,
    totalTokens: exact + estimated,
    exactTokens: exact,
    estimatedTokens: estimated,
    sourceIds: [...sources].sort(),
  };
}

async function loadSummary() {
  try {
    const summary = JSON.parse(await fetchText(SUMMARY_URL));
    if (typeof summary.total_tokens === "number" && summary.as_of) {
      return {
        asOf: summary.as_of,
        firstDate: summary.first_date,
        totalTokens: summary.total_tokens,
        exactTokens: summary.exact_tokens,
        estimatedTokens: summary.estimated_tokens,
        sourceIds: summary.sources ?? [],
        method: "summary.json",
      };
    }
  } catch {
    // Not published yet; fall through to the embedded daily record.
  }
  const html = await fetchText(DASHBOARD_URL);
  const daily = extractGlobal(html, "__DAILY_BURN__");
  if (!Array.isArray(daily) || daily.length < 100) {
    throw new Error("Daily record looks truncated; refusing to overwrite the snapshot.");
  }
  return { ...summarizeDaily(daily), method: "embedded daily record" };
}

const fmt = (n) => n.toLocaleString("en-US");
const short = (n) => `${Math.floor(n / 1e7) * 10}M+`;
const millions = (n) => `${(n / 1e6).toFixed(1)}M`;

const s = await loadSummary();
if (!/^\d{4}-\d{2}-\d{2}$/.test(s.asOf)) throw new Error(`Bad as-of date: ${s.asOf}`);
if (s.totalTokens < 5e8) throw new Error(`Total ${s.totalTokens} is below the last known floor; refusing.`);

const unknown = s.sourceIds.filter((id) => !SOURCE_LABELS[id]);
if (unknown.length) throw new Error(`Unlabeled sources: ${unknown.join(", ")}. Add labels to SOURCE_LABELS.`);
const pctExact = Math.round((s.exactTokens / s.totalTokens) * 100);

const body = `// GENERATED by scripts/fetch-ai-usage.mjs — do not edit by hand.
// Floor values derived from ${DASHBOARD_URL} via ${s.method}.
// Refreshed on a schedule by .github/workflows/refresh-ai-usage.yml; never fetched at runtime.
export const aiUsageSnapshot = {
  url: "${DASHBOARD_URL}",
  asOf: "${s.asOf}",
  firstDate: "${s.firstDate}",
  totalTokensRaw: ${s.totalTokens},
  totalTokens: "${fmt(s.totalTokens)}",
  totalTokensShort: "${short(s.totalTokens)}",
  exactTokens: "${millions(s.exactTokens)}",
  estimatedTokens: "${millions(s.estimatedTokens)}",
  percentExact: ${pctExact},
  sourceCount: ${s.sourceIds.length},
  sourceLabels: ${JSON.stringify(s.sourceIds.map((id) => SOURCE_LABELS[id]))},
} as const;
`;

// The no-JS fallback in index.html carries the same figures between markers.
const indexPath = resolve(root, "index.html");
const indexHtml = await readFile(indexPath, "utf8");
const startMarker = "<!-- ai-usage-snapshot:start (rewritten by scripts/fetch-ai-usage.mjs) -->";
const endMarker = "<!-- ai-usage-snapshot:end -->";
const a = indexHtml.indexOf(startMarker);
const b = indexHtml.indexOf(endMarker);
if (a < 0 || b < 0 || b < a) throw new Error("index.html is missing the ai-usage-snapshot markers.");
const paragraph = `\n          <p>Floor figures as of ${s.asOf}: ${fmt(s.totalTokens)} tokens recovered across ${s.sourceIds.length} sources, spanning ${s.firstDate} through ${s.asOf}, at ${millions(s.exactTokens)} exact-metered and ${millions(s.estimatedTokens)} estimated.</p>\n          `;
const nextIndex = indexHtml.slice(0, a + startMarker.length) + paragraph + indexHtml.slice(b);
if (nextIndex !== indexHtml) {
  await writeFile(indexPath, nextIndex, "utf8");
  console.log("index.html no-JS fallback figures updated.");
}

let previous = "";
try { previous = await readFile(target, "utf8"); } catch { /* first run */ }
if (previous === body) {
  console.log(`ai-usage snapshot unchanged (as of ${s.asOf}, ${fmt(s.totalTokens)} tokens).`);
} else {
  await writeFile(target, body, "utf8");
  console.log(`ai-usage snapshot updated: as of ${s.asOf}, ${fmt(s.totalTokens)} tokens across ${s.sourceIds.length} sources (${s.method}).`);
}
